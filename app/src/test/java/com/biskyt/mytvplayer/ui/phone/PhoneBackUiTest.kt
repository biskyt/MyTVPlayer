/** The back arrow on the phone's film and series pages (from MyPlexPlayer's review, 2026-11-25). */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34], application = TestApp::class, qualifiers = "w390dp-h844dp-xxhdpi")
class PhoneBackUiTest {
    @get:Rule val compose = createUiComposeRule()

    @get:Rule(order = Navigators.ORDER)
    val navigators = Navigators()

    private val provider = FakeProvider()
    private val app = ApplicationProvider.getApplicationContext<TestApp>()
    private var pid = 0L

    @Before
    fun setUp() = runBlocking {
        shadowOf(app.packageManager).setSystemFeature(PackageManager.FEATURE_TOUCHSCREEN, true)
        autoFindsTv = { false } // the phone layout (TestApp sets the TV's)
        pid = app.container.addHomeTv(provider, vod = true)
    }

    @After
    fun tearDown() = provider.close()

    @Test
    fun `Back on a film page with nothing under it goes to Home`() {
        // As when a film is opened from the TV's home screen or a link: the page is the only one.
        val navigator = navigators.new(Screen.MovieDetails(pid, 501))
        compose.setContent {
            MyTvTheme {
                Box(Modifier.fillMaxSize().background(Palette.background)) { NavHost(remember { navigator }) { ScreenContent(it) } }
            }
        }
        val back = hasContentDescription("Back")
        compose.waitAdvancingClock(stepMs = 50) { compose.onAllNodes(back).fetchSemanticsNodes().isNotEmpty() }
        compose.onAllNodes(back)[0].performClick()
        compose.waitAdvancingClock(stepMs = 50) { navigator.current.screen == Screen.Home }
    }
}
